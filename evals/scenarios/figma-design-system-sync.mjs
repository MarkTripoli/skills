import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { expect, failures } from "../lib.mjs";

// A local export exercises import ownership and a plan-only delta without a Figma account,
// framework SDK, or live app. Real rendering and production implementation are not proven here.
const GUIDANCE = "# Prototype author guidance\nKeep source generated by the design author.\n";
const PRODUCTION = ":root { --blue-600: #2255aa; --action-background: var(--blue-600); --body-weight: 400; }\n";
const BUTTON = 'export const button = { label: "Save", className: "primary", width: 120 };\n';
const SELECTED = {
  "src/theme.css": ":root { --primary: #3366cc; --body-weight: 500; }\n",
  "src/Panel.tsx": 'import "./theme.css";\nexport default function Panel() { return <button style={{ width: 240 }}><img src="/assets/save.svg" />Save</button>; }\n',
  "assets/save.svg": '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 8 8"><path d="M1 1h6v6H1z"/></svg>\n',
  "package.json": '{"name":"sample-prototype","private":true,"version":"1.0.0"}\n',
  "package-lock.json": '{"name":"sample-prototype","lockfileVersion":3,"packages":{}}\n',
};
const EXCLUDED = {
  "AGENTS.md": "# Export guidance\nThis export is only a visual reference.\n",
  "dist/generated.js": "// generated build output\n",
  "node_modules/example/index.js": "// dependency directory\n",
};
const write = (root, name, text) => {
  const file = path.join(root, name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};
const contents = (file) => fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;

export default {
  slug: "sample-design-sync",
  title: "Import a local prototype and derive a repository-owned design-system delta",
  workflow: "oneshot",
  fixtures: [],
  request: "Import prototype.zip and compare its design system with the prior reference. Plan only, with no production changes.",
  phases: [{
    skill: "figma-design-system-sync",
    terminal: true,
    request: "Use this checkout. Import prototype.zip into the reference destination specified by AGENTS.md, preserving repository-owned guidance and excluding generated state. Write sync-delta.md at the repository root with the exact old and new colors and weights, the production semantic role and owners, layout exclusions, and the checks still needed. This is import and planning only: do not edit production, run its checks, publish, or commit. No Figma connection is available or needed.",
    setup: async ({ repo }) => {
      write(repo, "AGENTS.md", "# Repository instructions\nImported prototype reference lives in .design/reference/. Production tokens live in src/theme.css and the primary button consumer is src/button.js. The reference is design-author owned. Preserve its existing AGENTS.md during imports. Prototype layout is not production layout.\n");
      write(repo, "src/theme.css", PRODUCTION);
      write(repo, "src/button.js", BUTTON);
      write(repo, ".design/reference/AGENTS.md", GUIDANCE);
      write(repo, ".design/reference/src/theme.css", ":root { --primary: #2255aa; --body-weight: 400; }\n");
      write(repo, ".design/reference/src/Panel.tsx", 'export default function Panel() { return <button style={{ width: 120 }}>SAVE</button>; }\n');
      const staging = fs.mkdtempSync(path.join(os.tmpdir(), "sample-figma-export-"));
      try {
        for (const [name, text] of Object.entries({ ...SELECTED, ...EXCLUDED })) write(staging, name, text);
        execFileSync("zip", ["-q", path.join(repo, "prototype.zip"), ...Object.keys(SELECTED), ...Object.keys(EXCLUDED)], { cwd: staging });
      } finally {
        fs.rmSync(staging, { recursive: true, force: true });
      }
    },
    check: ({ live, repo, answer }) => {
      if (!live) return [];
      const delta = contents(path.join(repo, "sync-delta.md"));
      const text = `${answer}\n${delta ?? ""}`;
      return failures(
        ...Object.entries(SELECTED).map(([name, bytes]) => contents(path.join(repo, ".design/reference", name)) === bytes ? null : `figma sync: selected ZIP member was not imported byte-for-byte: ${name}`),
        contents(path.join(repo, ".design/reference/AGENTS.md")) === GUIDANCE ? null : "figma sync: replaced repository-owned prototype guidance",
        ...["dist/generated.js", "node_modules/example/index.js"].map((name) => fs.existsSync(path.join(repo, ".design/reference", name)) ? `figma sync: imported generated state: ${name}` : null),
        contents(path.join(repo, "src/theme.css")) === PRODUCTION && contents(path.join(repo, "src/button.js")) === BUTTON ? null : "figma sync: changed production during a plan-only request",
        delta === null ? "figma sync: no comparison record was saved" : null,
        expect.matches("figma sync: exact prior color", text, /#2255aa/i),
        expect.matches("figma sync: exact new color", text, /#3366cc/i),
        expect.matches("figma sync: prior and new weights", text, /400[\s\S]*500/),
        expect.matches("figma sync: production semantic role", text, /action-background/),
        expect.matches("figma sync: prototype geometry stays outside scope", text, /\b(layout|geometry|width)\b[\s\S]{0,180}\b(exclud|out.of.scope|non.goal|not|unchanged|preserv)|\b(exclud|out.of.scope|non.goal|not|unchanged|preserv)[\s\S]{0,180}\b(layout|geometry|width)\b/i),
        expect.matches("figma sync: source checksum recorded", text, /\b[a-f0-9]{64}\b/i),
        expect.matches("figma sync: live UI proof still needed", text, /\b(live|device|browser)\b/i),
      );
    },
  }],
};
